/**
 * App-wide Material 3 theme.
 *
 * On Android 12+ (API 31+) this pulls [dynamicLightColorScheme] /
 * [dynamicDarkColorScheme], which derive the entire color scheme from the
 * user's device wallpaper. On older devices it falls back to a static,
 * seed-based Deep Purple scheme defined in Color.kt.
 */
@Composable
fun ComposeDynamicColorDemoTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    // Dynamic color is only available on Android 12+.
    dynamicColor: Boolean = true,
    content: @Composable () -> Unit
) {
    val dynamicColorSupported = Build.VERSION.SDK_INT >= Build.VERSION_CODES.S
    val colorScheme = when {
        dynamicColor && dynamicColorSupported -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
